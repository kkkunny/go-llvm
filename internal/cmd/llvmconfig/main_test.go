// TestDiscoverLLVMConfigOrder 覆盖探测顺序与显式配置不可用时的报错。
func TestDiscoverLLVMConfigOrder(t *testing.T) {
	notFound := func(string) (string, error) { return "", exec.ErrNotFound }

	t.Run("LLVM_CONFIG 优先于 LLVM_PREFIX 与 PATH", func(t *testing.T) {
		got, err := discoverLLVMConfig(envMap(map[string]string{
			"LLVM_CONFIG": "/custom/llvm-config",
			"LLVM_PREFIX": "/prefix",
		}), func(name string) (string, error) {
			if name != "/custom/llvm-config" {
				t.Fatalf("命中 LLVM_CONFIG 后不应继续查询 %s", name)
			}
			return name, nil
		})
		if err != nil || got != "/custom/llvm-config" {
			t.Fatalf("got=%q err=%v，期望 /custom/llvm-config", got, err)
		}
	})

	t.Run("LLVM_PREFIX 拼接 bin/llvm-config", func(t *testing.T) {
		want := filepath.Join("/prefix", "bin", "llvm-config")
		got, err := discoverLLVMConfig(envMap(map[string]string{"LLVM_PREFIX": "/prefix"}),
			func(name string) (string, error) {
				if name != want {
					t.Fatalf("查询了 %s，期望 %s", name, want)
				}
				return name, nil
			})
		if err != nil || got != want {
			t.Fatalf("got=%q err=%v，期望 %q", got, err, want)
		}
	})

	t.Run("PATH 优先 llvm-config-22", func(t *testing.T) {
		var tried []string
		got, err := discoverLLVMConfig(envMap(nil), func(name string) (string, error) {
			tried = append(tried, name)
			if name == "llvm-config-22" {
				return "/usr/bin/llvm-config-22", nil
			}
			return "", exec.ErrNotFound
		})
		if err != nil || got != "/usr/bin/llvm-config-22" {
			t.Fatalf("got=%q err=%v，期望 /usr/bin/llvm-config-22", got, err)
		}
		if len(tried) != 1 {
			t.Fatalf("命中 llvm-config-22 后不应继续查询：%v", tried)
		}
	})

	t.Run("PATH 退回 llvm-config", func(t *testing.T) {
		got, err := discoverLLVMConfig(envMap(nil), func(name string) (string, error) {
			if name == "llvm-config" {
				return "/usr/bin/llvm-config", nil
			}
			return "", exec.ErrNotFound
		})
		if err != nil || got != "/usr/bin/llvm-config" {
			t.Fatalf("got=%q err=%v，期望 /usr/bin/llvm-config", got, err)
		}
	})

	t.Run("显式 LLVM_CONFIG 不可执行时直接报错", func(t *testing.T) {
		_, err := discoverLLVMConfig(envMap(map[string]string{"LLVM_CONFIG": "/missing/llvm-config"}), notFound)
		if err == nil || !strings.Contains(err.Error(), "/missing/llvm-config") {
			t.Fatalf("应报出不可执行的显式路径：%v", err)
		}
	})

	t.Run("全部缺失时报错", func(t *testing.T) {
		_, err := discoverLLVMConfig(envMap(nil), notFound)
		if err == nil || !strings.Contains(err.Error(), "找不到 llvm-config") {
			t.Fatalf("应报找不到 llvm-config：%v", err)
		}
	})
}

